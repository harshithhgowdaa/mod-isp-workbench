"""Render the reproducible single-block, browser-only judge showcase."""
import base64
import json
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import app

ASSET_DIR = ROOT / "static" / "showcase"
DEMO_DIR = ROOT / "static" / "demo"


def save_data_url(value: str, path: Path) -> None:
    _, encoded = value.split(",", 1)
    path.write_bytes(base64.b64decode(encoded))


def main() -> None:
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    source_path = DEMO_DIR / "siddcc_scene0164_block01_input.png"
    reference_path = DEMO_DIR / "siddcc_scene0164_block01_reference.png"
    with Image.open(source_path) as image:
        source = image.convert("RGB").copy()
    with Image.open(reference_path) as image:
        reference = image.convert("RGB").copy()
    if source.size != (256, 256) or reference.size != source.size:
        raise ValueError("Expected aligned 256×256 SIDD-CC demo images.")

    result = app.process_decoded(
        source,
        "SIDD-CC held-out sRGB · scene 0164 · block 1 of 928",
        None,
        "rgb",
        {},
        reference,
        mode="human",
        strength=1.0,
        style=None,
    )
    save_data_url(result["input"], ASSET_DIR / "input.jpg")
    save_data_url(result["outputs"]["classical"]["image"], ASSET_DIR / "classical.jpg")
    save_data_url(result["outputs"]["learned"]["image"], ASSET_DIR / "learned.jpg")
    save_data_url(result["outputs"]["hybrid"]["image"], ASSET_DIR / "hybrid.jpg")
    save_data_url(
        "data:image/png;base64," + base64.b64encode(reference_path.read_bytes()).decode("ascii"),
        ASSET_DIR / "reference.png",
    )
    metadata = {
        "dataset": "SIDD-CC sRGB test split",
        "scene_id": "0164",
        "block_index": 1,
        "block_count": 928,
        "width": source.width,
        "height": source.height,
        "scope": "Single held-out test block. It is not the aggregate 928-block benchmark.",
        "method": "Current workbench outputs, generated by app.process_decoded; human profile, strength 1.0, no CNILUT style.",
        "paths": {
            name: {
                "latency_ms": output["latency_ms"],
                "metrics": output.get("metrics"),
                "reused_inference": output.get("reused_inference", False),
            }
            for name, output in result["outputs"].items()
        },
        "aggregate_srgb_test": {
            "blocks": 928,
            "psnr_db": 33.755,
            "ssim": 0.7757,
            "scope": "Separate reported SIDD-CC sRGB benchmark evaluation; not this single block.",
        },
    }
    (ASSET_DIR / "results.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
